def esc(x):
    return str(x).replace('|', '/').replace('\n', '<br>')


def table(headers, rows):
    out = ['| ' + ' | '.join(headers) + ' |',
           '| ' + ' | '.join(['---'] * len(headers)) + ' |']
    for r in rows:
        out.append('| ' + ' | '.join(esc(x) for x in r) + ' |')
    return '\n'.join(out)


def f(x, d=1):
    if x is None:
        return '—'
    if isinstance(x, float) and abs(x - round(x)) < 1e-9:
        return str(int(round(x)))
    return f'{x:.{d}f}'


def pct(x):
    return f'{x*100:.0f}%'


